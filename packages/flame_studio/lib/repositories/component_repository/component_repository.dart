import 'package:flame_studio/repositories/repositories.dart';
import 'package:path/path.dart' as p;

/// {@template invalid_component_name_exception}
/// Thrown when creating a [Component] with a name that is not a valid
/// identifier.
/// {@endtemplate}
class const InvalidComponentNameException(
  /// The rejected name.
  final String name,
) implements Exception {
  /// {@macro invalid_component_name_exception}
  this;
}

/// {@template component_already_exists_exception}
/// Thrown when creating a [Component] whose name is already taken.
/// {@endtemplate}
class const ComponentAlreadyExistsException(
  /// The name that is already taken.
  final String name,
) implements Exception {
  /// {@macro component_already_exists_exception}
  this;
}

/// {@template component_class_conflict_exception}
/// Thrown when creating a [Component] whose generated class would have the
/// same name as a class generated for another component, such as `AB` and
/// `a_b`, or `player_ship_head` and the `head` child of `player_ship`.
/// {@endtemplate}
class const ComponentClassConflictException(
  /// The rejected name.
  final String name,

  /// The name of the component that already generates the class.
  final String conflictingComponent,
) implements Exception {
  /// {@macro component_class_conflict_exception}
  this;
}

/// {@template generated_file_conflict_exception}
/// Thrown when the code of a [Component] would overwrite a file that was
/// not generated by the editor.
/// {@endtemplate}
class const GeneratedFileConflictException(
  /// The path of the file that was kept.
  final String path,
) implements Exception {
  /// {@macro generated_file_conflict_exception}
  this;
}

/// {@template invalid_palette_exception}
/// Thrown when saving a [Palette] with a color name that can't be used,
/// see [Palette.validateColorName].
/// {@endtemplate}
class const InvalidPaletteException(
  /// The rejected palette.
  final Palette palette,
) implements Exception {
  /// {@macro invalid_palette_exception}
  this;
}

/// {@template component_repository}
/// Lists, creates, saves and deletes the components of a project.
///
/// Each component is stored as `<name>.json` inside the
/// [componentsDirectory] of the project folder, and its Dart code is
/// generated by the [ComponentCodeGenerator] inside the output folder of
/// the project.
///
/// The [Palette] shared by the components is stored in the [paletteFile]
/// of the project folder, and its Dart code is generated by the
/// [PaletteCodeGenerator] in the same output folder as the components.
/// {@endtemplate}
class ComponentRepository({
  required final FileSystemClient _fileSystem,
  final ComponentCodeGenerator _codeGenerator = const ComponentCodeGenerator(),
  final PaletteCodeGenerator _paletteCodeGenerator =
      const PaletteCodeGenerator(),
}) {
  /// {@macro component_repository}
  this;

  /// Folder, relative to the project folder, where components are stored.
  static const componentsDirectory = '.flame_studio/components';

  /// File, relative to the project folder, where the palette is stored.
  static const paletteFile = '.flame_studio/palette.json';

  static final _validName = RegExp(r'^[A-Za-z_][A-Za-z0-9_]*$');

  /// Returns the components of the project at [projectPath], sorted by name.
  ///
  /// Component files that cannot be read are skipped.
  Future<List<Component>> getComponents(String projectPath) async {
    final files = await _fileSystem.listFiles(
      _directory(projectPath),
      extension: '.json',
    );

    final components = <Component>[];
    for (final file in files) {
      try {
        final json = jsonDecode(await _fileSystem.readFile(file));
        components.add(Component.fromJson(json as Map<String, dynamic>));
      } on Object {
        continue;
      }
    }
    return components..sort((a, b) => a.name.compareTo(b.name));
  }

  /// Creates a component of [type] called [name], with default properties,
  /// in the project at [projectPath]. Polygons start with the vertices of
  /// [polygonShape].
  ///
  /// Throws an [InvalidComponentNameException] if [name] is not a valid
  /// identifier or doesn't make a valid class name (such as `_1`), or if
  /// its code would take the place of the palette's (`palette`), or a
  /// [ComponentAlreadyExistsException] if a component with that name, or
  /// one that generates the same file (such as `playerShip` and
  /// `PlayerShip`), already exists. Throws a
  /// [ComponentClassConflictException] if another component already
  /// generates its class (see [ComponentTree.generatedClassNames]).
  ///
  /// Hitboxes ([ComponentType.isHitbox]) can only be children, so [type]
  /// can't be one: that throws an [ArgumentError].
  Future<Component> createComponent(
    String projectPath,
    String name,
    ComponentType type, {
    PolygonShape polygonShape = PolygonShape.triangle,
  }) async {
    if (type.isHitbox) {
      throw ArgumentError.value(type, 'type', 'Hitboxes can only be children');
    }
    final className = dartClassName(name);
    final fileName = dartFileName(name);
    if (!_validName.hasMatch(name) ||
        !isDartIdentifier(className) ||
        fileName == PaletteCodeGenerator.baseName) {
      throw InvalidComponentNameException(name);
    }

    final existing = await _fileSystem.listFiles(
      _directory(projectPath),
      extension: '.json',
    );
    if (existing.any(
      (file) => dartFileName(p.basenameWithoutExtension(file)) == fileName,
    )) {
      throw ComponentAlreadyExistsException(name);
    }

    final rootClass = dartRootClassName(name);
    for (final other in await getComponents(projectPath)) {
      if (other.generatedClassNames.contains(rootClass)) {
        throw ComponentClassConflictException(name, other.name);
      }
    }

    final component = Component.create(name, type, polygonShape: polygonShape);
    await _write(projectPath, component);
    return component;
  }

  /// Saves [component] in the project at [projectPath], replacing the
  /// previously stored version.
  Future<void> saveComponent(String projectPath, Component component) {
    return _write(projectPath, component);
  }

  /// Writes the Dart code of [component] to the folder [outputPath],
  /// relative to the project at [projectPath], replacing the previously
  /// generated code.
  ///
  /// Paints that use colors of the project's palette reference them, so
  /// the code of the palette is written too, keeping the reference valid.
  ///
  /// Throws a [GeneratedFileConflictException] if the file exists but was
  /// not generated by the editor, or is the palette's (a component named
  /// `palette` created before the name was reserved); it is never
  /// overwritten.
  Future<void> writeComponentCode(
    String projectPath,
    String outputPath,
    Component component,
  ) async {
    final path = _codeFile(projectPath, outputPath, component);
    if (_codeGenerator.fileName(component) == PaletteCodeGenerator.fileName) {
      throw GeneratedFileConflictException(path);
    }
    await _writeGenerated(path, () async {
      final palette = await getPalette(projectPath);
      if (component.usedPaletteColors.any(palette.contains)) {
        await writePaletteCode(projectPath, outputPath, palette);
      }
      return _codeGenerator.generate(component, palette: palette);
    });
  }

  /// Returns the palette of the project at [projectPath].
  ///
  /// Returns an empty palette if none was saved or the stored data is
  /// unreadable.
  Future<Palette> getPalette(String projectPath) async {
    final path = p.join(projectPath, paletteFile);
    try {
      if (!await _fileSystem.fileExists(path)) {
        return const Palette();
      }
      return Palette.fromJson(jsonDecode(await _fileSystem.readFile(path)));
    } on Object {
      return const Palette();
    }
  }

  /// Saves [palette] as the palette of the project at [projectPath].
  ///
  /// Throws an [InvalidPaletteException] if a color has a name that can't
  /// be used (see [Palette.validateColorName]).
  Future<void> savePalette(String projectPath, Palette palette) async {
    if (!palette.isValid) {
      throw InvalidPaletteException(palette);
    }
    await _fileSystem.writeFile(
      p.join(projectPath, paletteFile),
      jsonEncode(palette.toJson()),
    );
  }

  /// Writes the Dart code of [palette] to the folder [outputPath], relative
  /// to the project at [projectPath], replacing the previously generated
  /// code.
  ///
  /// Throws a [GeneratedFileConflictException] if the file exists but was
  /// not generated by the editor; it is never overwritten.
  Future<void> writePaletteCode(
    String projectPath,
    String outputPath,
    Palette palette,
  ) {
    return _writeGenerated(
      p.join(projectPath, outputPath, PaletteCodeGenerator.fileName),
      () async => _paletteCodeGenerator.generate(palette),
    );
  }

  /// Writes the code built by [generate] to [path], unless a file that was
  /// not generated by the editor is there.
  Future<void> _writeGenerated(
    String path,
    Future<String> Function() generate,
  ) async {
    if (await _fileSystem.fileExists(path) && !await _isGenerated(path)) {
      throw GeneratedFileConflictException(path);
    }
    await _fileSystem.writeFile(path, await generate());
  }

  /// Whether the folder [outputPath], relative to the project at
  /// [projectPath], holds the code currently generated for [component].
  ///
  /// It doesn't when the code was never generated, was generated for an
  /// older version of the component, or the file in its place was not
  /// generated by the editor.
  Future<bool> isComponentCodeUpToDate(
    String projectPath,
    String outputPath,
    Component component,
  ) async {
    final path = _codeFile(projectPath, outputPath, component);
    if (!await _fileSystem.fileExists(path)) {
      return false;
    }
    final palette = await getPalette(projectPath);
    return await _fileSystem.readFile(path) ==
        _codeGenerator.generate(component, palette: palette);
  }

  /// Deletes [component] from the project at [projectPath], along with its
  /// generated code in the folder [outputPath].
  ///
  /// A file in place of the generated code that was not generated by the
  /// editor is kept.
  Future<void> deleteComponent(
    String projectPath,
    Component component, {
    required String outputPath,
  }) async {
    await _fileSystem.deleteFile(_file(projectPath, component.name));
    final code = _codeFile(projectPath, outputPath, component);
    if (await _fileSystem.fileExists(code) && await _isGenerated(code)) {
      await _fileSystem.deleteFile(code);
    }
  }

  Future<bool> _isGenerated(String path) async {
    final contents = await _fileSystem.readFile(path);
    return contents.startsWith(ComponentCodeGenerator.header);
  }

  String _codeFile(String projectPath, String outputPath, Component component) {
    return p.join(projectPath, outputPath, _codeGenerator.fileName(component));
  }

  Future<void> _write(String projectPath, Component component) {
    return _fileSystem.writeFile(
      _file(projectPath, component.name),
      jsonEncode(component.toJson()),
    );
  }

  String _directory(String projectPath) =>
      p.join(projectPath, componentsDirectory);

  String _file(String projectPath, String name) =>
      p.join(_directory(projectPath), '$name.json');
}
