import 'package:dart_style/dart_style.dart';
import 'package:flame_studio/repositories/component_repository/code_generation/dart_names.dart';
import 'package:flame_studio/repositories/repositories.dart';
import 'package:pub_semver/pub_semver.dart';

/// {@template palette_code_generator}
/// Generates the Dart source of a [Palette]: a class with a `Color`
/// constant for every color, which the code of the components that use
/// them references (`GamePalette.primary`).
///
/// Generated component classes all start with `$`, so [className] never
/// clashes with them.
/// {@endtemplate}
class const PaletteCodeGenerator() {
  /// {@macro palette_code_generator}
  this;

  /// The name of the generated class.
  static const className = 'GamePalette';

  /// The name, without extension, of the generated file. Components can't
  /// use it (see [ComponentRepository.createComponent]).
  static const baseName = 'palette';

  /// The name of the generated file, in the output folder of the project,
  /// next to the code of the components.
  static const fileName = '$baseName${ComponentCodeGenerator.fileExtension}';

  static final _formatter = DartFormatter(languageVersion: Version(3, 8, 0));

  /// The expression of the color called [name] in the generated code.
  static String reference(String name) => '$className.${dartMemberName(name)}';

  /// Returns the formatted Dart source of [palette].
  String generate(Palette palette) {
    final buffer = StringBuffer()
      ..writeln(ComponentCodeGenerator.header)
      ..writeln('// Generated by Flame Studio.')
      ..writeln()
      ..writeln('// coverage:ignore-file')
      ..writeln('// ignore_for_file: type=lint')
      ..writeln()
      ..writeln("import 'dart:ui';")
      ..writeln()
      ..writeln('/// The colors of the game palette.')
      ..writeln('abstract final class $className {');
    for (final PaletteColor(:name, :color) in palette.colors) {
      buffer
        ..writeln('  /// The `$name` color.')
        ..writeln(
          '  static const ${dartMemberName(name)} = '
          '${ComponentCodeGenerator.colorLiteral(color)};',
        )
        ..writeln();
    }
    buffer.writeln('}');
    return _formatter.format(buffer.toString());
  }
}
