/// {@template component_editor_view}
/// Shows the tree of the component being edited on the left, its preview
/// in the center, below a toolbar, and the properties of the selected node
/// on the right, below a top bar with the project actions (such as the
/// palette).
///
/// Changes are saved with the save button or Cmd/Ctrl+S. The preview zooms
/// in with Cmd/Ctrl+=, out with Cmd/Ctrl+- and back to 100% with
/// Cmd/Ctrl+0.
/// {@endtemplate}
class const ComponentEditorView({
  /// The project the component belongs to.
  required final Project project,
  super.key,
}) extends StatelessWidget {
  /// {@macro component_editor_view}
  this;

  /// Width of the component tree panel.
  static const treePanelWidth = 240.0;

  /// Width of the properties panel.
  static const propertiesPanelWidth = 320.0;

  @override
  Widget build(BuildContext context) {
    final bloc = context.read<ComponentEditorBloc>();
    void save() => bloc.add(const ComponentEditorSaveRequested());
    void zoomIn() => bloc.add(const ComponentEditorZoomedIn());
    void zoomOut() => bloc.add(const ComponentEditorZoomedOut());
    void resetZoom() => bloc.add(const ComponentEditorZoomReset());

    return BlocListener<ComponentEditorBloc, ComponentEditorState>(
      listenWhen: (previous, current) => previous.status != current.status,
      listener: (context, state) {
        final message = switch (state.status) {
          ComponentEditorStatus.failure => 'Could not save the component',
          ComponentEditorStatus.codeConflict =>
            'Saved, but the code was not generated: a file that was not '
                'generated by the editor is in the way',
          ComponentEditorStatus.classConflict => _classConflictMessage(state),
          ComponentEditorStatus.codeFailure =>
            'Saved, but the code could not be generated',
          _ => null,
        };
        if (message != null) {
          ScaffoldMessenger.of(context)
            ..hideCurrentSnackBar()
            ..showSnackBar(SnackBar(content: Text(message)));
        }
      },
      child: CallbackShortcuts(
        bindings: {
          const SingleActivator(LogicalKeyboardKey.keyS, meta: true): save,
          const SingleActivator(LogicalKeyboardKey.keyS, control: true): save,
          ...zoomShortcuts(
            onZoomIn: zoomIn,
            onZoomOut: zoomOut,
            onReset: resetZoom,
          ),
        },
        child: _UnsavedChangesGuard(
          child: Focus(
            autofocus: true,
            child: Scaffold(
              appBar: AppBar(
                title: const _Title(),
                actions: [_SaveButton(onPressed: save)],
              ),
              body: Column(
                crossAxisAlignment: CrossAxisAlignment.stretch,
                children: [
                  EditorTopBar(project: project),
                  const Divider(height: 1),
                  Expanded(
                    child: Row(
                      crossAxisAlignment: CrossAxisAlignment.stretch,
                      children: [
                        const SizedBox(
                          width: treePanelWidth,
                          child: ComponentTreePanel(),
                        ),
                        const VerticalDivider(width: 1),
                        const Expanded(
                          child: Column(
                            crossAxisAlignment: CrossAxisAlignment.stretch,
                            children: [
                              EditorToolbar(),
                              Divider(height: 1),
                              Expanded(child: ComponentPreview()),
                            ],
                          ),
                        ),
                        const VerticalDivider(width: 1),
                        SizedBox(
                          width: propertiesPanelWidth,
                          child: PropertiesPanel(project: project),
                        ),
                      ],
                    ),
                  ),
                ],
              ),
            ),
          ),
        ),
      ),
    );
  }

  /// Tells how to fix each clash: children can be renamed here, but the
  /// root can't (and neither can components), so a clash of the root class
  /// must be fixed in the other component, or by deleting one of the two.
  static String _classConflictMessage(ComponentEditorState state) {
    final rootClass = state.component.generatedClassName;
    final rootOwner = state.rootClassOwner;
    final childClashes = [
      for (final MapEntry(key: className, value: owner)
          in state.conflictingClassNames.entries)
        if (className != rootClass)
          '$className (also generated by "${owner.name}")',
    ];
    final rootFix = switch (rootOwner) {
      null => null,
      Component(:final name, :final generatedClassName)
          when generatedClassName == rootClass =>
        '"$name" generates the same class, $rootClass: delete one of the '
            'two components.',
      Component(:final name) =>
        'A child of "$name" generates $rootClass, the class of this '
            'component: rename that child.',
    };
    final childrenFix = childClashes.isEmpty
        ? null
        : 'Rename the children that generate ${childClashes.join(', ')}.';
    return ["This component can't be saved.", ?rootFix, ?childrenFix].join(' ');
  }
}

/// Asks what to do with unsaved changes before the editor is left.
class const _UnsavedChangesGuard({required final Widget child})
    extends StatelessWidget {
  @override
  Widget build(BuildContext context) {
    final hasChanges = context.select<ComponentEditorBloc, bool>(
      (bloc) => bloc.state.hasChanges,
    );
    return PopScope<void>(
      canPop: !hasChanges,
      onPopInvokedWithResult: (didPop, _) {
        if (!didPop) {
          unawaited(_confirmLeave(context));
        }
      },
      child: child,
    );
  }

  Future<void> _confirmLeave(BuildContext context) async {
    final bloc = context.read<ComponentEditorBloc>();
    final navigator = Navigator.of(context);

    final decision = await UnsavedChangesDialog.show(context);
    switch (decision) {
      case UnsavedChangesDecision.cancel:
        return;
      case UnsavedChangesDecision.discard:
        navigator.pop();
      case UnsavedChangesDecision.save:
        // A save that finished while the dialog was open saved everything.
        if (!bloc.state.hasChanges) {
          return navigator.pop();
        }
        bloc.add(const ComponentEditorSaveRequested());
        // Edits keep the saving status, so the first other status is the
        // result of the save (or of the one already running).
        final state = await bloc.stream.firstWhere(
          (state) => state.status != ComponentEditorStatus.saving,
          orElse: () => bloc.state,
        );
        // The editor was closed meanwhile.
        if (bloc.isClosed) {
          return;
        }
        // When not saved the editor stays open and shows the error. Edits
        // made while saving keep it open too, so they are not lost.
        if (state.status.isSaved && !state.hasChanges) {
          navigator.pop();
        }
    }
  }
}

class const _Title() extends StatelessWidget {
  @override
  Widget build(BuildContext context) {
    final (name, hasChanges) = context
        .select<ComponentEditorBloc, (String, bool)>(
          (bloc) => (bloc.state.component.name, bloc.state.hasChanges),
        );
    return Text(hasChanges ? '$name •' : name);
  }
}

class const _SaveButton({required final VoidCallback onPressed})
    extends StatelessWidget {
  @override
  Widget build(BuildContext context) {
    final canSave = context.select<ComponentEditorBloc, bool>(
      (bloc) => bloc.state.canSave,
    );
    return IconButton(
      tooltip: 'Save',
      icon: const Icon(Icons.save_outlined),
      onPressed: canSave ? onPressed : null,
    );
  }
}
