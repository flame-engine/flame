import 'package:flame_studio/component_editor/widgets/property_editors/color_field.dart';
import 'package:flame_studio/palette/palette.dart';
import 'package:flame_studio/repositories/repositories.dart';
import 'package:flutter/material.dart';
import 'package:flutter_bloc/flutter_bloc.dart';

/// {@template palette_view}
/// Lists the colors of the palette to add, rename, change and remove
/// them, and pops with the palette once it is saved.
///
/// Colors used by components can't be renamed or removed.
/// {@endtemplate}
class const PaletteView({super.key}) extends StatelessWidget {
  /// {@macro palette_view}
  this;

  @override
  Widget build(BuildContext context) {
    return BlocConsumer<PaletteBloc, PaletteState>(
      listenWhen: (previous, current) => previous.status != current.status,
      listener: (context, state) {
        if (!state.status.isSaved) {
          return;
        }
        final message = switch (state.status) {
          PaletteStatus.codeConflict =>
            'Palette saved, but its code was not generated: a file that was '
                'not generated by the editor is in the way',
          PaletteStatus.codeFailure =>
            'Palette saved, but its code could not be generated',
          _ => null,
        };
        if (message != null) {
          ScaffoldMessenger.of(context)
            ..hideCurrentSnackBar()
            ..showSnackBar(SnackBar(content: Text(message)));
        }
        Navigator.of(context).pop(state.palette);
      },
      builder: (context, state) {
        final bloc = context.read<PaletteBloc>();
        final loading =
            state.status == PaletteStatus.initial ||
            state.status == PaletteStatus.loading;

        return AlertDialog(
          title: const Text('Palette'),
          content: SizedBox(
            width: 520,
            child: loading
                ? const Center(
                    heightFactor: 1,
                    child: CircularProgressIndicator(),
                  )
                : Column(
                    mainAxisSize: MainAxisSize.min,
                    crossAxisAlignment: CrossAxisAlignment.stretch,
                    children: [
                      if (state.entries.isEmpty)
                        const Padding(
                          padding: EdgeInsets.symmetric(vertical: 16),
                          child: Text(
                            'No colors yet. Named colors added here can be '
                            'picked in any color field.',
                          ),
                        ),
                      Flexible(
                        child: ListView(
                          shrinkWrap: true,
                          children: [
                            for (final (index, entry) in state.entries.indexed)
                              _PaletteEntryRow(
                                key: ValueKey(entry.id),
                                entry: entry,
                                users: state.usersOf(entry),
                                error: state.palette.validateColorName(
                                  index,
                                  entry.color.name,
                                ),
                              ),
                          ],
                        ),
                      ),
                      const SizedBox(height: 8),
                      Align(
                        alignment: AlignmentDirectional.centerStart,
                        child: TextButton.icon(
                          icon: const Icon(Icons.add),
                          label: const Text('Add color'),
                          onPressed: state.isEditable
                              ? () => bloc.add(const PaletteColorAdded())
                              : null,
                        ),
                      ),
                      if (state.status == PaletteStatus.failure)
                        Text(
                          'Something went wrong',
                          style: TextStyle(
                            color: Theme.of(context).colorScheme.error,
                          ),
                        ),
                    ],
                  ),
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.of(context).pop(),
              child: const Text('Cancel'),
            ),
            FilledButton(
              onPressed: state.canSave
                  ? () => bloc.add(const PaletteSaveRequested())
                  : null,
              child: const Text('Save'),
            ),
          ],
        );
      },
    );
  }
}

class const _PaletteEntryRow({
  required final PaletteEntry entry,

  /// The components that use the color.
  required final List<String> users,
  required final PaletteColorNameError? error,
  super.key,
}) extends StatelessWidget {
  @override
  Widget build(BuildContext context) {
    final bloc = context.read<PaletteBloc>();
    final inUse = users.isNotEmpty;
    final usedBy = 'Used by ${users.join(', ')}';
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 6),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        spacing: 8,
        children: [
          Expanded(
            child: TextFormField(
              initialValue: entry.color.name,
              readOnly: inUse,
              decoration: InputDecoration(
                labelText: 'Name',
                isDense: true,
                helperText: inUse ? usedBy : null,
                // A color in use can't be renamed, so the other one with
                // the same name shows the error.
                errorText: switch (inUse ? null : error) {
                  null => null,
                  PaletteColorNameError.invalid =>
                    'Must be a valid Dart identifier',
                  PaletteColorNameError.duplicate =>
                    'Another color has this name',
                },
              ),
              onChanged: (name) =>
                  bloc.add(PaletteColorRenamed(entry.id, name)),
            ),
          ),
          SizedBox(
            width: 180,
            child: ColorField(
              label: 'Color',
              value: entry.color.color,
              onChanged: (color) =>
                  bloc.add(PaletteColorValueChanged(entry.id, color)),
            ),
          ),
          IconButton(
            tooltip: inUse ? "$usedBy, so it can't be removed" : 'Remove',
            icon: const Icon(Icons.delete_outline),
            onPressed: inUse
                ? null
                : () => bloc.add(PaletteColorRemoved(entry.id)),
          ),
        ],
      ),
    );
  }
}
