import 'package:flame_studio/repositories/repositories.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  group(PaletteCodeGenerator, () {
    const generator = PaletteCodeGenerator();

    test('fileName is next to the generated components', () {
      expect(PaletteCodeGenerator.fileName, equals('palette.generated.dart'));
    });

    test('reference is the camelCase member of the class', () {
      expect(
        PaletteCodeGenerator.reference('dark_grey'),
        equals('GamePalette.darkGrey'),
      );
    });

    test('generates a constant for every color', () {
      expect(
        generator.generate(
          const Palette(
            colors: [
              PaletteColor(name: 'primary', color: 0xFFFF0000),
              PaletteColor(name: 'dark_grey', color: 0x00333333),
            ],
          ),
        ),
        equals('''
// GENERATED CODE - DO NOT MODIFY BY HAND.
// Generated by Flame Studio.

// coverage:ignore-file
// ignore_for_file: type=lint

import 'dart:ui';

/// The colors of the game palette.
abstract final class GamePalette {
  /// The `primary` color.
  static const primary = Color(0xFFFF0000);

  /// The `dark_grey` color.
  static const darkGrey = Color(0x00333333);
}
'''),
      );
    });

    test('generates an empty class for an empty palette', () {
      expect(
        generator.generate(const Palette()),
        contains('abstract final class GamePalette {}'),
      );
    });
  });
}
